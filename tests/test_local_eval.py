def test_leave_one_out_memories_exclude_the_findings_own_label_and_short_notes():
    from gapscan.evaluation.local import leave_one_out_memories
    from gapscan.memory import retrieve

    own = LocalLabel(
        "src/a/x.ts", 10, "fs-filename", True, "userId comes from a request header"
    )
    sibling = LocalLabel(
        "src/a/y.ts", 20, "fs-filename", True, "userId comes from a request header, unchecked"
    )
    noted_safe = LocalLabel(
        "src/b/z.ts", 5, "html-template", False, "value is generated by the server"
    )
    terse = LocalLabel("src/a/w.ts", 7, "fs-filename", False, "ok")
    mems = leave_one_out_memories([own, sibling, noted_safe, terse], own)
    assert [m.text for m in mems] == [
        sibling.note,
        noted_safe.note,
    ]  # not its own, not the terse one
    assert mems[0].kind == "confirmed" and mems[1].kind == "false_positive"
    assert mems[0].path == "src/a" and mems[0].rule == "fs-filename"
    # a sibling in the same folder and rule is retrieved for the finding; the unrelated one is not
    f = finding("src/a/x.ts", 10, "javascript.audit.detect-non-literal-fs-filename")
    assert [m.text for m in retrieve(mems, f)] == [sibling.note]



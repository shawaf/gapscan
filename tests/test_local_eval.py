from __future__ import annotations

import json
from pathlib import Path

from gapscan.config import Config
from gapscan.evaluation import runner
from gapscan.evaluation.local import (
    LocalLabel,
    load_local_labels,
    load_local_targets,
    match_label,
    run_local,
)
from gapscan.models import Category, Finding, ScanResult, Severity


def finding(file="a.ts", line=10, rule="javascript.lang.detect-non-literal-fs-filename", **kw):
    return Finding(scanner="semgrep", rule_id=rule, title="t", severity=Severity.MEDIUM,
                   category=Category.CODE, file=file, start_line=line, **kw)  # fmt: skip


def test_match_label_needs_file_rule_and_line_within_tolerance():
    real = LocalLabel("a.ts", 10, "non-literal-fs", True, "n")
    other = LocalLabel("a.ts", 50, "non-literal-fs", False, "n")
    labels = [real, other]
    assert match_label(finding(line=12), labels) is real  # within 2 lines
    assert match_label(finding(line=13), labels) is None
    assert match_label(finding(file="b.ts"), labels) is None
    assert match_label(finding(rule="other-rule"), labels) is None
    assert match_label(finding(line=50), labels) is other  # nearest label wins
    assert match_label(finding().model_copy(update={"start_line": None}), labels) is None


def test_targets_and_labels_load_with_relative_paths(tmp_path):
    (tmp_path / "t.toml").write_text(
        '[[target]]\nname = "x"\npath = "~/proj"\nscan_subdir = "src"\nlabels = "x.json"\n'
    )
    (tmp_path / "x.json").write_text(json.dumps({"labels": [
        {"file": "a.ts", "line": 3, "rule": "sql", "vulnerable": True, "note": "why"},
        {"file": "b.ts", "line": 4, "rule": "xss", "vulnerable": False},
    ]}))  # fmt: skip
    t = load_local_targets(tmp_path / "t.toml")["x"]
    assert t.labels == tmp_path / "x.json" and t.path == Path("~/proj").expanduser()
    labels = load_local_labels(t.labels)
    assert labels[0].vulnerable and labels[1].note == "" and not labels[1].vulnerable
    assert load_local_targets(tmp_path / "missing.toml") == {}


def test_run_local_scores_only_labeled_findings_and_reports_the_rest(tmp_path, monkeypatch):
    proj = tmp_path / "proj"
    (proj / "src").mkdir(parents=True)
    labels = tmp_path / "l.json"
    labels.write_text(json.dumps({"labels": [
        {"file": "a.ts", "line": 10, "rule": "sql", "vulnerable": True, "note": "real"},
        {"file": "b.ts", "line": 5, "rule": "xss", "vulnerable": False, "note": "server value"},
        {"file": "gone.ts", "line": 1, "rule": "x", "vulnerable": True, "note": "no finding"},
    ]}))  # fmt: skip
    found = [
        finding("a.ts", 10, "x.sql-injection"),
        finding("b.ts", 5, "x.xss-template"),
        finding("c.ts", 7, "x.unlabeled"),
    ]
    monkeypatch.setattr(
        "gapscan.evaluation.local.run_scan",
        lambda cfg, root: ScanResult(target=str(root), findings=found),
    )
    from gapscan.evaluation.local import LocalTarget

    out = run_local(
        Config(data={"dir": str(tmp_path)}),
        LocalTarget(name="x", path=proj, scan_subdir="src", labels=labels),
        triage=False,
    )
    assert (out["findings"], out["labeled"], out["unlabeled"]) == (3, 2, 1)
    assert out["scanner_precision_on_labeled"] == 0.5
    assert out["labels_without_finding"] == ["gone.ts:1 x"]


